/// Server-side texts of the demo backend in the languages it serves.
///
/// The backend answers in the language of `Accept-Language` (`ru`, `en` or
/// `uz`, Russian otherwise): names, descriptions and rejection messages. Data
/// is stored language-neutral (ids and keys) and named when a response is
/// built, so switching the language never changes stored state.
abstract final class DemoTexts {
  static const languages = ['ru', 'en', 'uz'];

  /// The first supported primary language subtag of an `Accept-Language`
  /// value, or Russian.
  static String negotiate(String? acceptLanguage) {
    for (final part in (acceptLanguage ?? '').split(',')) {
      final tag = part.split(';').first.trim().toLowerCase();
      final primary = tag.split(RegExp('[-_]')).first;
      if (languages.contains(primary)) return primary;
    }
    return 'ru';
  }

  /// Text [key] in [language]; `{name}` placeholders are filled from [args].
  /// An unknown key is returned as is, which tests catch.
  static String text(
    String language,
    String key, [
    Map<String, Object?> args = const {},
  ]) {
    var value = (catalogue[language] ?? catalogue['ru']!)[key] ?? key;
    for (final entry in args.entries) {
      value = value.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return value;
  }

